use clippy_utils::diagnostics::span_lint_and_help;
use rustc_ast::token::CommentKind;
use rustc_ast::{AttrArgs, AttrKind, AttrStyle, Attribute, ExprKind};
use rustc_lint::{EarlyContext, EarlyLintPass, LintContext};
use rustc_lint_defs::{declare_lint, declare_lint_pass};
use rustc_span::sym;

declare_lint! {
    /// Checks for documentation written any way but `///` and `//!` lines: block doc comments
    /// (`/** */` and `/*! */`), `#[doc = "..."]` and `#![doc = "..."]` attributes, and `doc`
    /// attributes whose value a macro generates, such as `#[doc = concat!(..)]` or
    /// `#![doc = include_str!("../README.md")]`. Attributes that are not documentation text,
    /// such as `#[doc(hidden)]` or `#[doc(alias = "..")]`, and docs a macro expansion writes,
    /// are left alone. A macro's input carries its doc comments as `doc` attributes, so a `doc`
    /// attribute is read as what its source text is: `///` and `//!` lines pass, as when an item
    /// with docs is passed to a `macro_rules!` macro.
    ///
    /// The Google Rust Style Guide, "When and how to write documentation": use `///` comments
    /// for items and `//!` comments for modules and crates, and "prefer to document things in
    /// a straightforward manner, using `///` and `//!` comments, rather than generating
    /// documentation from macros. This makes the documentation directly readable when viewing
    /// or modifying the source code."
    ///
    /// This covers a crate root's `#![doc = include_str!("../README.md")]` too, and a crate root
    /// can't carry an `expect`, since `suppression_policy` rejects every inner lint level. A
    /// published library writes its docs.rs front page as `//!` lines in the crate root, while
    /// crates.io shows the README through `readme` in `Cargo.toml`.
    ///
    /// ```rust,ignore
    /// /** Returns the price for one order. */
    /// fn price(order: &Order) -> u64 { /* ... */ }
    ///
    /// #[doc = concat!("The most an ", "order pays.")]
    /// const MAX_PRICE: u64 = 1_000;
    /// ```
    ///
    /// Use instead:
    ///
    /// ```rust,ignore
    /// /// Returns the price for one order.
    /// fn price(order: &Order) -> u64 { /* ... */ }
    ///
    /// /// The most an order pays.
    /// const MAX_PRICE: u64 = 1_000;
    /// ```
    pub DOC_ATTRIBUTE_STYLE,
    Warn,
    "documentation written as a block comment, a `doc` attribute or a macro's output rather \
     than `///` or `//!` lines"
}

declare_lint_pass!(DocAttributeStyle => [DOC_ATTRIBUTE_STYLE]);

const GUIDE: &str = "as the Google Rust Style Guide's \"When and how to write documentation\" asks";

impl EarlyLintPass for DocAttributeStyle {
    fn check_attribute(&mut self, cx: &EarlyContext<'_>, attr: &Attribute) {
        if attr.span.from_expansion() {
            return;
        }
        let line = match attr.style {
            AttrStyle::Outer => "///",
            AttrStyle::Inner => "//!",
        };
        let message = match &attr.kind {
            AttrKind::DocComment(CommentKind::Block, _) => "block doc comment",
            AttrKind::DocComment(CommentKind::Line, _)
            | AttrKind::Synthetic(_)
            | AttrKind::Generated(_) => return,
            AttrKind::Normal(normal) => {
                if !attr.has_name(sym::doc) {
                    return;
                }
                let source = cx.sess().source_map().span_to_snippet(attr.span);
                match source.as_deref().map(|source| source.get(..3)) {
                    Ok(Some("///" | "//!")) => return,
                    Ok(Some("/**" | "/*!")) => "block doc comment",
                    _ => {
                        let AttrArgs::Eq { expr, .. } = &normal.item.args else {
                            return;
                        };
                        if matches!(expr.kind, ExprKind::Lit(_)) && !expr.span.from_expansion() {
                            "documentation in a `doc` attribute"
                        } else {
                            "documentation generated by a macro in a `doc` attribute"
                        }
                    }
                }
            }
        };
        span_lint_and_help(
            cx,
            DOC_ATTRIBUTE_STYLE,
            attr.span,
            message,
            None,
            format!("write the documentation out as `{line}` lines, {GUIDE}"),
        );
    }
}

#[test]
fn ui() {
    crate::ui_harness::ui_test(DOC_ATTRIBUTE_STYLE);
}
