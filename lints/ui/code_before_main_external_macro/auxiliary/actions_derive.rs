//! A derive like GPUI's `Action`, which writes an inherent impl whose function registers a builder
//! through the facade's re-export of the registry, as `gpui_macros` does with
//! `gpui::private::inventory::submit!`.

#![crate_type = "proc-macro"]

extern crate proc_macro;

use proc_macro::{TokenStream, TokenTree};

#[proc_macro_derive(Action)]
pub fn derive_action(item: TokenStream) -> TokenStream {
    let name = type_name(&item);
    format!(
        "impl {name} {{
            fn __autogenerated() {{
                fn __build_{name}() {{}}
                ::gui::private::registry::submit! {{ __build_{name} }}
            }}
        }}"
    )
    .parse()
    .unwrap()
}

fn type_name(item: &TokenStream) -> String {
    let mut trees = item.clone().into_iter();
    while let Some(tree) = trees.next() {
        if let TokenTree::Ident(keyword) = &tree
            && keyword.to_string() == "struct"
            && let Some(TokenTree::Ident(name)) = trees.next()
        {
            return name.to_string();
        }
    }
    panic!("`Action` derives only on a struct")
}
