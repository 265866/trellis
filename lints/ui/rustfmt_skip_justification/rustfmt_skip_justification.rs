// Inner tool attributes need this feature.
#![feature(custom_inner_attributes)]

// Flagged: a bare skip, even with a comment above it.
#[rustfmt::skip]
const BARE: [u32; 3] = [ 1,  2,  3];

// Flagged: the form that skips macro calls.
#[rustfmt::skip::macros(vec)]
fn macros() -> Vec<u32> {
    vec![ 1,  2,  3]
}

mod generated {
    // Flagged: an inner skip.
    #![rustfmt::skip]

    pub const TABLE: [u32; 3] = [ 1,  2,  3];
}

// Not flagged: the `expect` on the same item gives the reason, and is fulfilled.
#[cfg_attr(
    dylint_lib = "trellis_lints",
    expect(rustfmt_skip_justification, reason = "manual alignment: one column per shelf")
)]
#[rustfmt::skip]
const ALIGNED: [[u32; 3]; 2] = [
    [  2,  5,  10],
    [ 20, 50, 100],
];

// Not flagged: a plain `expect` works the same way.
#[expect(rustfmt_skip_justification, reason = "generated by `tools/price_table.py`")]
#[rustfmt::skip]
const GENERATED: [u32; 3] = [ 1,  2,  3];

mod generated_with_reason {
    // Not flagged: an inner skip with an inner `expect`.
    #![expect(rustfmt_skip_justification, reason = "generated by `tools/price_table.py`")]
    #![rustfmt::skip]

    pub const TABLE: [u32; 3] = [ 1,  2,  3];
}

// rustc reports this `expect` unfulfilled, since no skip sits under it: proof that the
// fulfilled ones above really were.
#[expect(rustfmt_skip_justification, reason = "nothing to justify")]
const FORMATTED: [u32; 3] = [1, 2, 3];

fn statements() -> u32 {
    // Not flagged: a statement whose skip has an `expect`.
    #[expect(rustfmt_skip_justification, reason = "manual alignment")]
    #[rustfmt::skip]
    let aligned = [ 1,  2,  3];

    // Flagged: a statement with a bare skip.
    #[rustfmt::skip]
    let unaligned = [ 1,  2,  3];

    aligned[0] + unaligned[0]
}

// Not flagged: an `expect` on a `macro_rules!` works too.
#[expect(rustfmt_skip_justification, reason = "keeps rustfmt out of the macro body")]
#[rustfmt::skip]
macro_rules! skipped_const {
    ($name:ident) => {
        #[rustfmt::skip]
        const $name: u32 = 1;
    };
}

// Not flagged: the attribute comes from a macro expansion.
skipped_const!(EXPANDED);

// Flagged: a skip inside `cfg_attr`, whatever the predicate, which rustfmt honors in any build;
// an `expect` on the item doesn't cover it.
#[cfg_attr(target_os = "freebsd", rustfmt::skip)]
const FREEBSD: [u32; 3] = [ 1,  2,  3];

#[cfg_attr(windows, rustfmt::skip)]
const WINDOWS: [u32; 3] = [ 1,  2,  3];

#[expect(rustfmt_skip_justification, reason = "manual alignment")]
#[cfg_attr(unix, cfg_attr(windows, rustfmt::skip::macros(vec)))]
fn nested() -> Vec<u32> {
    vec![ 1,  2,  3]
}

mod conditionally_generated {
    #![cfg_attr(unix, rustfmt::skip)]

    pub const TABLE: [u32; 3] = [ 1,  2,  3];
}

// Not flagged: a `cfg_attr` around other attributes.
#[cfg_attr(windows, derive(Debug))]
struct Order;

fn main() {
    let _ = (macros(), statements(), nested(), FREEBSD, WINDOWS, Order);
}
